#!/usr/bin/env python3
"""Regenerate every phase-1 result into ``experiments/output/``.

This is a reproduction script, not a library: it runs each fixture, checks it
against its own hand calculation, writes the sweep tables and figures, and
summarises the findings in Markdown. It exits non-zero if any fixture disagrees
with its arithmetic, so it also serves as an end-to-end check.

    python experiments/run_phase1_study.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from wildfireguardian_assisted_dispatch.cli.plotting import (
    has_matplotlib,
    plot_feasibility,
)
from wildfireguardian_assisted_dispatch.feasibility.exact import (
    ExactSolverUnavailable,
    exact_feasible_set,
)
from wildfireguardian_assisted_dispatch.feasibility.refine import refine_transitions
from wildfireguardian_assisted_dispatch.feasibility.sensitivity import (
    sweep_pickup_durations,
)
from wildfireguardian_assisted_dispatch.fixtures import FIXTURES, load
from wildfireguardian_assisted_dispatch.missions.evaluator import evaluate_mission
from wildfireguardian_assisted_dispatch.scenarios.io import HAVE_PARQUET, write_rows
from wildfireguardian_assisted_dispatch.service.pickup import (
    PICKUP_SENSITIVITY_MINUTES,
)
from wildfireguardian_assisted_dispatch.validation.handcalc import check_fixture

OUTPUT = Path(__file__).parent / "output"
TABLE_SUFFIX = ".parquet" if HAVE_PARQUET else ".csv"


def fmt(windows) -> str:
    return " U ".join(f"[{a:g}, {b:g}]" for a, b in windows) or "empty"


def main() -> int:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Phase 1 results",
        "",
        "Regenerated by `experiments/run_phase1_study.py`. Every window below is",
        "checked against the fixture's own hand calculation, not against a",
        "previous run.",
        "",
        "| fixture | title | expected T (sampled) | grid sweep | exact solver | agrees |",
        "|---|---|---|---|---|---|",
    ]
    failures = 0

    for key in FIXTURES:
        fixture = load(key)
        sweep = fixture.sweep()
        feasible = sweep.feasible_set(fixture.threshold)
        check = check_fixture(fixture)
        failures += 0 if check.ok else 1

        write_rows(sweep.rows(), OUTPUT / f"fixture_{key}_sweep{TABLE_SUFFIX}")
        if has_matplotlib():
            plot_feasibility(
                sweep.grid, sweep.p_success, feasible,
                OUTPUT / f"fixture_{key}_feasibility.png",
                title=f"Fixture {key.upper()}: {fixture.title}",
            )

        try:
            exact = exact_feasible_set(
                fixture.spec, fixture.ensemble,
                (fixture.grid[0], fixture.grid[-1]), threshold=fixture.threshold)
            exact_text = fmt((c.lo, c.hi) for c in exact.components)
        except ExactSolverUnavailable:
            exact_text = "n/a (conditions not met)"

        lines.append(
            f"| `{key}` | {fixture.title} | {fmt(fixture.expected_windows)} | "
            f"{fmt(feasible.intervals)} | {exact_text} | "
            f"{'yes' if check.ok else '**NO**'} |"
        )
        print(check.describe())

    # -- the non-monotonic result, refined below grid resolution ------------
    f = load("f")
    transitions = refine_transitions(f.spec, f.ensemble, f.sweep(), tolerance=0.001)
    lines += ["", "## Fixture F: feasibility is not monotone in dispatch time", ""]
    lines.append(f"Feasible set: **{fmt(f.feasible_set().intervals)}** "
                 f"with gap(s) {fmt(f.feasible_set().gaps)}.")
    lines.append("")
    for transition in transitions:
        lines.append(f"- {transition.describe()}")
    lines += [
        "",
        "Dispatching at t = 5 fails; dispatching at t = 12 succeeds. No waiting is",
        "involved in either case - only the phase of the corridor's timeline",
        "differs. `sup T = 13` is therefore a true statement about the supremum",
        "and a false statement about the set.",
    ]

    # -- the mid-edge closure comparison ------------------------------------
    strict, myopic = load("g"), load("g_myopic")
    caught = evaluate_mission(myopic.spec, 6.0, myopic.ensemble.scenarios[0])
    lines += ["", "## Fixture G: what entry-time-only hazard checking costs", ""]
    lines.append(f"- full-interval admission: T = {fmt(strict.feasible_set().intervals)}")
    lines.append(f"- entry-time-only admission: T = {fmt(myopic.feasible_set().intervals)}")
    lines.append("")
    lines.append("At t = 6 the entry-only planner produces:")
    lines.append("")
    lines.append("```")
    lines.append(caught.render())
    lines.append("```")

    # -- pickup sensitivity --------------------------------------------------
    d = load("d")
    sensitivity = sweep_pickup_durations(d.spec, d.ensemble, d.grid,
                                         PICKUP_SENSITIVITY_MINUTES)
    write_rows(sensitivity.rows(), OUTPUT / "pickup_sensitivity.csv")
    lines += ["", "## Fixture D: pickup sensitivity", "",
               "| pickup (min) | latest feasible dispatch | feasible windows |",
               "|---|---|---|"]
    for case in sensitivity.cases:
        lines.append(f"| {case.duration:g} | {case.latest_feasible:g} | "
                     f"{case.feasible_set.format_intervals()} |")
    lines += [
        "",
        "On-scene time comes off the dispatch envelope minute for minute",
        "(`t <= 30 - p`). These durations are scenario parameters; they are **not**",
        "validated medical or triage categories.",
        "",
        "---",
        "",
        "Generated results assume full foresight within each scenario",
        "(docs/ASSUMPTIONS.md A-008), so every feasible set above is an optimistic",
        "upper bound.",
    ]

    (OUTPUT / "summary.md").write_text("\n".join(lines) + "\n")
    print()
    print(f"wrote {OUTPUT}/summary.md and {len(list(OUTPUT.iterdir()))} artefact(s)")
    if failures:
        print(f"{failures} fixture(s) disagree with their hand calculations",
              file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
